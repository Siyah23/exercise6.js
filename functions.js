//Create a function called greet that takes a name parameter and return "Hello, [name]!"
function greet(name){ 
  return "Hello, " + name + "!";
}

//Create a function called add that takes two parameters and return the sum of both parameters
function add(x, y){
  return x + y
}

//Call both functions and store their results in variables 
const message = greet("Siyamthanda")
let sum = add(11, 12)

//Print the results to the console 
console.log(message);
console.log(sum);
